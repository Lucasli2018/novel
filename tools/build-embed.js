#!/usr/bin/env node
/**
 * build-embed.js —— 生成 assets/data.js
 *
 * 把 books.json、codex/codex.json 以及所有章节 .md 正文内联为一个 JS 全局变量
 * window.__EMBED__，使站点在 file:// 直接双击打开时也能正常读取数据
 * （浏览器禁止 file:// 下的 fetch，但允许 <script src> 加载本地 JS）。
 *
 * 用法：
 *   node tools/build-embed.js
 *
 * 之后 index.html 在 file:// 下走内联数据，在 http(s) 下优先 fetch 实时 JSON。
 */
const fs = require("fs");
const path = require("path");

const root = path.dirname(path.dirname(__filename)); // novel/
const booksPath = path.join(root, "books.json");
const codexPath = path.join(root, "codex", "codex.json");
const outPath = path.join(root, "assets", "data.js");

function readJSON(p) {
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

const books = readJSON(booksPath);
const codex = readJSON(codexPath);

const chapters = {};
let missing = 0;
for (const b of books.books) {
  for (const c of b.chapters) {
    for (const lang of ["zh", "en"]) {
      const rel = c[lang];
      const full = path.join(root, rel);
      if (fs.existsSync(full)) {
        chapters[rel] = fs.readFileSync(full, "utf8");
      } else {
        missing++;
        console.error("MISSING chapter file:", rel);
      }
    }
  }
}

const payload = { books, codex, chapters };
const out =
  "// AUTO-GENERATED by tools/build-embed.js — do not edit by hand.\n" +
  "// 本地 file:// 双击打开时使用，线上 http(s) 优先 fetch 实时 JSON。\n" +
  "window.__EMBED__ = " +
  JSON.stringify(payload) +
  ";\n";

fs.writeFileSync(outPath, out, "utf8");
console.log(
  `Wrote ${outPath}\n  books: ${books.books.length}\n  codex: ${codex.length}\n  chapters embedded: ${Object.keys(chapters).length}` +
    (missing ? `\n  WARNING: ${missing} chapter file(s) missing` : "")
);
